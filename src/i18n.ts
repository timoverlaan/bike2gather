const dicts: Record<Lang, Record<Key, string>> = { en, nl };
let current: Lang = 'en';

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}
export const getLang = () => current;

export function detectLang(): Lang {
  return navigator.language?.toLowerCase().startsWith('nl') ? 'nl' : 'en';
}

export function t(k: Key, vars: Record<string, string | number> = {}): string {
  let s = dicts[current][k] ?? en[k] ?? k;
  for (const [name, v] of Object.entries(vars)) s = s.replaceAll(`{${name}}`, String(v));
  return s;
}

/** Locale-aware number with one decimal. */
export const num = (x: number, digits = 1) =>
  x.toLocaleString(current === 'nl' ? 'nl-NL' : 'en-GB', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });

